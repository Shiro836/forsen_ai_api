CREATE TABLE IF NOT EXISTS messages (
    id                UUID,
    updated           UInt64 CODEC(Delta, ZSTD(1)),
    channel_id        UUID,
    channel_login     LowCardinality(String),
    twitch_user_id    UInt64,
    twitch_login      String CODEC(ZSTD(1)),
    reward_id         LowCardinality(String),
    reward_type       Int8,
    card_id           Nullable(UUID),
    card_name         LowCardinality(String),
    handler           LowCardinality(String),
    status            Int8,
    outcome           LowCardinality(String),
    message           String CODEC(ZSTD(3)),
    ai_response       String CODEC(ZSTD(3)),
    request_spans     String CODEC(ZSTD(1)),
    reply_spans       String CODEC(ZSTD(1)),
    image_ids         Array(String),
    show_images       Nullable(Bool),
    enqueued_at       DateTime64(3, 'UTC') CODEC(DoubleDelta, ZSTD(1)),
    started_at        Nullable(DateTime64(3, 'UTC')),
    finished_at       Nullable(DateTime64(3, 'UTC')),
    error             String CODEC(ZSTD(1)),
    llm_calls         UInt16,
    prompt_tokens     UInt32,
    completion_tokens UInt32,
    tts_tracks        UInt16,
    audio_sec         Float32,
    played_sec        Float32,
    filter_llm_hits   UInt16,
    filter_regex_hits UInt16,
    data              String CODEC(ZSTD(3)),
    archive           String CODEC(ZSTD(3))
) ENGINE = ReplacingMergeTree(updated)
PARTITION BY toYYYYMM(enqueued_at)
ORDER BY (channel_id, enqueued_at, id)
